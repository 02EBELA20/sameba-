const QUEUE_KEY = 'DEVOTIONAL_QUEUE_V4';
const LAST_ITEM_KEY = 'DEVOTIONAL_LAST_ITEM_V4';

function shuffle<T>(items: T[]): T[] {
  const array = [...items];

  for (let i = array.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [array[i], array[j]] = [array[j], array[i]];
  }

  return array;
}

async function saveQueue(queue: DevotionalItem[]) {
  await AsyncStorage.setItem(QUEUE_KEY, JSON.stringify(queue));
}

async function getSavedQueue(): Promise<DevotionalItem[]> {
  const raw = await AsyncStorage.getItem(QUEUE_KEY);

  if (!raw) return [];

  try {
    const parsed = JSON.parse(raw);

    if (!Array.isArray(parsed)) return [];

    return parsed.filter(
      (item) =>
        item &&
        typeof item.id === 'string' &&
        typeof item.text === 'string' &&
        item.text.trim().length > 0
    );
  } catch {
    return [];
  }
}

async function getLastItemId(): Promise<string | null> {
  return AsyncStorage.getItem(LAST_ITEM_KEY);
}

async function saveLastItemId(id: string) {
  await AsyncStorage.setItem(LAST_ITEM_KEY, id);
}

export async function getNextDevotional(): Promise<DevotionalItem> {
  const lastId = await getLastItemId();
  let queue = await getSavedQueue();

  if (queue.length === 0) {
    queue = shuffle(DEVOTIONALS);

    if (lastId && queue.length > 1 && queue[queue.length - 1]?.id === lastId) {
      const swapIndex = queue.findIndex((item) => item.id !== lastId);

      if (swapIndex >= 0) {
        const lastIndex = queue.length - 1;
        [queue[lastIndex], queue[swapIndex]] = [queue[swapIndex], queue[lastIndex]];
      }
    }
  }

  const next = queue.pop() ?? DEVOTIONALS[0];

  await saveQueue(queue);
  await saveLastItemId(next.id);

  return next;
}

export async function resetDevotionalQueue(): Promise<void> {
  await AsyncStorage.removeItem(QUEUE_KEY);
  await AsyncStorage.removeItem(LAST_ITEM_KEY);
}

export async function getRemainingDevotionalCount(): Promise<number> {
  const queue = await getSavedQueue();
  return queue.length;
}

export function getDevotionalVerseById(id: string): DevotionalItem | undefined {
  return DEVOTIONALS.find((item) => item.id === id);
}

export function getDevotionalVerseByNumericId(id: number): DevotionalItem | undefined {
  return DEVOTIONALS[id - 1];
}

export function getRandomDevotionalVerse(excludeIds?: Array<string | number>): DevotionalItem {
  const excludedSet = new Set((excludeIds || []).map(String));
  const available = DEVOTIONALS.filter((item) => !excludedSet.has(String(item.id)));

  if (available.length === 0) {
    return DEVOTIONALS[Math.floor(Math.random() * DEVOTIONALS.length)];
  }

  return available[Math.floor(Math.random() * available.length)];
}

export async function scheduleDevotionalNotifications(options: {
  enabled: boolean;
  intervalHours: 1 | 3 | 6 | 12 | 24;
  count?: number;
}): Promise<void> {
  await Notifications.cancelAllScheduledNotificationsAsync();

  if (!options.enabled) return;

  const notificationCount = options.count ?? 30;
  const intervalSeconds = options.intervalHours * 60 * 60;

  for (let i = 1; i <= notificationCount; i += 1) {
    const devotional = await getNextDevotional();

    await Notifications.scheduleNotificationAsync({
      content: {
        title: `${devotional.book} ${devotional.chapter}:${devotional.verse}`,
        body: devotional.text,
        data: {
          devotionalId: devotional.id,
          book: devotional.book,
          chapter: devotional.chapter,
          verse: devotional.verse,
        },
      },
      trigger: {
        seconds: intervalSeconds * i,
      } as Notifications.TimeIntervalTriggerInput,
    });
  }
}